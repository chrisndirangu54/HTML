import test from 'node:test';
import assert from 'node:assert/strict';
import {STAGES,SOURCES,validStage,validSource,isExactParametric,transitionModel,stageForHash} from '../assets/js/engineering-pipeline-core.mjs';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
test('one ordered pipeline replaces four independent sidebar modules',()=>{
 const html=read('engineering.html'),dashboard=read('assets/js/engineering-dashboard.js');
 assert.deepEqual(STAGES,['brief','model','refine','analyze','deliver']);
 assert.match(html,/data-eng-view="pipeline"/);
 assert.doesNotMatch(html,/data-eng-view="(?:cad|ai|sculpt|analysis)"/);
 assert.match(html,/assets\/js\/engineering-pipeline\.js/);
 assert.match(dashboard,/pipeline:\{title:'Engineering design pipeline'/);
});
test('one viewport: sculpt-capable scene is central and duplicate CAD renderer suppressed',()=>{
 const pipeline=read('assets/js/engineering-pipeline.js');
 const cad=read('assets/js/engineering-cad-viewer.js');
 const preview=read('assets/js/engineering-fabrication-preview.js');
 assert.match(pipeline,/window\.TeknUnifiedEngineeringPipeline=true/);
 assert.match(cad,/if\(!window\.TeknUnifiedEngineeringPipeline\)init\(\)/);
 assert.match(pipeline,/visual\.append\(top,viewport,sourceInfo,simState,viewportNote\)/);
 assert.match(pipeline,/viewer\.previewPrimitive\('plate',viewport,values\)/);
 assert.match(preview,/new THREE\.WebGLRenderer/);
 assert.match(preview,/currentView=\{/);
 assert.match(preview,/export function showPlateSimulation/);
 assert.match(preview,/export function selectUnifiedView/);
 assert.match(pipeline,/window\.addEventListener\('eng:plate-simulation'/);
});
test('model provenance transitions disallow stale beam-analysis and parametric fabrication for meshes',()=>{
 for(const s of SOURCES)assert.equal(validSource(s),s);
 let a=transitionModel({source:'parametric',generation:0},{type:'mesh-edited'});
 assert.equal(a.source,'sculpted-parametric');
 assert.equal(a.beamSurrogateAvailable,false);
 assert.equal(a.requiresExplicitMeshSelection,true);
 a=transitionModel(a,{type:'mesh-edited'});
 assert.equal(a.source,'sculpted-parametric');
 a=transitionModel(a,{type:'ai-generated'});
 assert.equal(a.source,'ai');
 assert.equal(isExactParametric(a.source),false);
 a=transitionModel(a,{type:'mesh-edited'});
 assert.equal(a.source,'sculpted-ai');
 a=transitionModel(a,{type:'parametric-created'});
 assert.equal(a.source,'parametric');
 assert.equal(a.beamSurrogateAvailable,true);
 assert.throws(()=>transitionModel(a,{type:'certify'}));
 assert.match(read('assets/js/engineering-fabrication.js'),/requiresMeshSelection/);
 assert.match(read('assets/js/engineering-pipeline.js'),/source!=='parametric'/);
 assert.match(read('assets/css/engineering-dashboard.css'),/data-exact-plate="false"/);
});
test('deep links and Tripo results lead to the right pipeline context',()=>{
 assert.equal(validStage('not-a-stage'),'model');
 assert.equal(stageForHash('#fab-tripo'),'refine');
 assert.equal(stageForHash('#eng-cad'),'model');
 assert.equal(stageForHash('#eng-sim-controls'),'analyze');
 assert.equal(stageForHash('#fab-design'),'deliver');
 assert.equal(stageForHash('#missing'),null);
 const tripo=read('assets/js/engineering-tripo.js');
 assert.match(tripo,/view:'pipeline',stage:'refine'/);
 assert.match(tripo,/sourceType:'ai'/);
 const loader=read('assets/js/engineering-fabrication-preview.js');
 assert.match(loader,/eng:geometry-loaded/);
 assert.match(loader,/source!=='parametric'/);
});
test('active-scene exports remain explicitly user-triggered and free of cloud calls',()=>{
 const pipeline=read('assets/js/engineering-pipeline.js');
 assert.match(pipeline,/\$\('fab-sculpt-export'\)\?\.click\(\)/);
 assert.match(pipeline,/\$\('fab-sculpt-use'\)\?\.click\(\)/);
 assert.match(pipeline,/document\.addEventListener\('fab:sculpt-changed'/);
 assert.match(pipeline,/document\.addEventListener\('fab:edited-stl-ready'/);
 assert.doesNotMatch(pipeline,/fetch\(|httpsCallable|uploadBytes|PAYSTACK|sk_live|automaticManufacture/);
});
